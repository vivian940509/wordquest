def flattened_kana():
    cards = []
    for table in KANA_TABLES:
        for row in table["rows"]:
            for item in row:
                if not item:
                    continue
                hira, kata, romaji = item
                cards.append({"hiragana": hira, "katakana": kata, "romaji": romaji, "group": table["title"]})
    return cards
